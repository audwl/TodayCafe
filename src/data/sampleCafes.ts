function getVibeTags(name: string, category: string): VibeTag[] {
  const tags = [...(vibeOverrides[name] ?? [])];
  if (/베이커리|베이글/.test(category)) tags.push("베이커리");
  if (/로스터리/.test(category) || /로스터리/.test(name)) tags.push("로스터리");
  if (/ > 디저트/.test(category)) tags.push("디저트");
  return [...new Set(tags)];
}

